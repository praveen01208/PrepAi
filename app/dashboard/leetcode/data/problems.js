// Generates a deterministic daily problem based on calendar date (refreshes at midnight without DB)
export function getDailyProblem(date = new Date()) {
  const dayOfYear = Math.floor(
    (date - new Date(date.getFullYear(), 0, 0)) / 1000 / 60 / 60 / 24
  );
  // Pick deterministically using pseudo-random hash of year + dayOfYear
  const seed = (date.getFullYear() * 365 + dayOfYear) * 9301 + 49297;
  const index = Math.abs(seed) % PROBLEMS.length;
  return PROBLEMS[index];
}

// Picks a completely random problem on demand without DB
export function getRandomProblem(excludeId = null) {
  const pool = excludeId ? PROBLEMS.filter((p) => p.id !== excludeId) : PROBLEMS;
  const idx = Math.floor(Math.random() * pool.length);
  return pool[idx];
}
